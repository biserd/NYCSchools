import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { loadCityClassSizes,loadDistrictClassSizes,cityClassSizesEnabled } from '../server/cityClassSizes';
import { classAverage } from '../shared/city-class-size';
import { CityClassSizeContent } from '../client/src/components/CityClassSizes';

const db=new DatabaseSync(':memory:');
db.exec(`PRAGMA foreign_keys=ON;
  CREATE TABLE schools(dbn TEXT PRIMARY KEY,district INTEGER);
  INSERT INTO schools VALUES ('02M158',2),('01M034',1),('02M475',2),('84Q706',24),('02M015',12);`);
db.exec(readFileSync('migrations-d1/0017_citywide_class_sizes.sql','utf8'));
for(const file of ['releases','sections','caps']) db.exec(readFileSync(`dist/class-size-citywide/${file}.sql`,'utf8'));
const read=async <T extends Record<string,unknown>>(sql:string,params:string[]=[])=>db.prepare(sql).all(...params).map(r=>({...r})) as T[];
const elementary=await loadCityClassSizes('02M158',read);
assert.ok(elementary);
assert.equal(elementary.observedOn,'2026-10-31');
assert.equal(elementary.previousOn,'2025-10-31');
const k=elementary.rows.filter(r=>r.band==='K5'&&r.groupName==='K');
assert.equal(k.reduce((sum,r)=>sum+r.students,0),95);
assert.equal(k.reduce((sum,r)=>sum+r.classes,0),5);
assert.equal(k.reduce((sum,r)=>sum+(r.districtStudents??0),0),2052);
assert.equal(k.reduce((sum,r)=>sum+(r.districtClasses??0),0),102);
assert.equal(k.reduce((sum,r)=>sum+(r.previousStudents??0),0),92);
assert.ok(elementary.rows.some(r=>r.band==='K5'&&r.groupName==='5'));
assert.deepEqual(elementary.caps.find(c=>c.scope==='grade'&&c.groupName==='K'),{scope:'grade',groupName:'K',eligible:5,meeting:4});
const ms=await loadCityClassSizes('01M034',read), hs=await loadCityClassSizes('02M475',read);
assert.ok(ms?.rows.some(r=>r.band==='MS'&&r.department==='Math'&&r.previousStudents===null));
assert.ok(hs?.rows.some(r=>r.band==='HS'&&r.department==='English'));
assert.equal(await loadCityClassSizes('84Q706',read),null,'Do not infer a charter result');
assert.equal(await loadCityClassSizes('30Q472',read),null,'Do not expose records without a canonical profile');
assert.equal(classAverage(0,0),null);
assert.equal(classAverage(95,5),'19.0');
for(let district=1;district<=32;district++){
  const data=await loadDistrictClassSizes(district,read);
  assert.ok(data?.rows.every(row=>row.band==='K5'));
  assert.ok(data.rows.some(r=>r.groupName==='K'));
  assert.deepEqual(data.caps,[]);
}
let html=renderToStaticMarkup(<CityClassSizeContent data={elementary}/>);
assert.match(html,/4 of 5 reported classes met the cap/);
assert.match(html,/Oct 31, 2026/);
assert.match(html,/nofollow noopener noreferrer/);
assert.match(html,/District 2:/);
html=renderToStaticMarkup(<CityClassSizeContent data={hs!}/>);
assert.match(html,/same student can appear in several courses/);
assert.doesNotMatch(html,/Oct 31, 2025/);
assert.equal(db.prepare("SELECT COUNT(*) c FROM city_class_size_releases WHERE observed_on='2025-10-31'").get()!.c,2);
assert.equal(db.prepare("SELECT COUNT(*) c FROM city_class_size_releases WHERE observed_on='2026-06-15'").get()!.c,1);
process.env.ENVIRONMENT='production';
delete process.env.CITY_CLASS_SIZES_ENABLED;
assert.equal(cityClassSizesEnabled(),false);
process.env.CITY_CLASS_SIZES_ENABLED='true';
assert.equal(cityClassSizesEnabled(),true);
console.log('Citywide class sizes: passed source fixtures, 32 districts, October revisions, June isolation, course scope and missing-data checks.');
