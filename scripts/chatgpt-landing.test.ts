import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { ChatGPTPluginContent } from '../shared/ChatGPTPluginContent';
import { CHATGPT_FAQS, CHATGPT_PLUGIN, CHATGPT_PROMPTS, chatgptPluginSchemas } from '../shared/chatgpt-plugin';
import { renderSeoHtml } from '../server/seoRenderer';
import { sitemapByName } from '../server/seoFeeds';
import { isAgentPublicPage, publicPageMarkdown } from '../server/agentMarkdown';

const template=readFileSync('client/index.html','utf8');
const markup=renderToStaticMarkup(React.createElement(ChatGPTPluginContent));
const html=await renderSeoHtml(CHATGPT_PLUGIN.path,template);
assert.ok(html,'public landing page must be server rendered');
assert.equal((html.match(/<h1[ >]/g)||[]).length,1);
assert.ok(html.includes('<title>'+CHATGPT_PLUGIN.title.replaceAll('&','&amp;')+'</title>'));
assert.ok(html.includes('name="description" content="'+CHATGPT_PLUGIN.description+'"'));
assert.ok(html.includes('rel="canonical" href="https://nycschoolsratings.com/chatgpt"'));
assert.ok(html.includes('content="index, follow"'));
assert.equal(new URL(CHATGPT_PLUGIN.url).origin,'https://chatgpt.com');
assert.equal(CHATGPT_PLUGIN.url,CHATGPT_PLUGIN.url.trim());
assert.ok(!CHATGPT_PLUGIN.url.includes('\u00a0'));
assert.equal((markup.match(new RegExp(CHATGPT_PLUGIN.url,'g'))||[]).length,2,'hero and closing should use the same verified listing URL');
assert.ok(markup.includes('rel="noopener noreferrer nofollow"'));
assert.equal((html.match(/data-schema-type="BreadcrumbList"/g)||[]).length,1,'schema breadcrumbs must not be duplicated');
assert.equal((html.match(/data-schema-type="FAQPage"/g)||[]).length,1);
for(const faq of CHATGPT_FAQS) assert.ok(markup.includes(faq.question));
const schemas=chatgptPluginSchemas();
assert.equal(schemas.filter(s=>s['@type']==='FAQPage').length,1);
assert.equal(CHATGPT_PROMPTS.length,4);
for(const prompt of CHATGPT_PROMPTS) assert.ok(markup.includes(prompt.label));
for(const text of ['No NYC School Ratings subscription required','public school information','does not change ratings','not official NYCPS','private calendars','missing score is not a zero','2-K, 3-K','source years']) assert.ok(markup.includes(text),text);
assert.ok(!/guaranteed admission|every school is rated|free on every ChatGPT plan|OpenAI-approved/i.test(markup));
assert.ok(markup.includes('href="/methodology"'));
assert.ok(markup.includes('href="/pricing"'));
assert.ok(markup.includes('href="/map"'));
assert.ok(markup.includes('href="/contact"'));
assert.ok(markup.includes('href="/privacy"'));
assert.ok(markup.includes('href="/terms"'));
const sitemap=await sitemapByName('static');
assert.equal((sitemap?.match(/<loc>https:\/\/nycschoolsratings\.com\/chatgpt<\/loc>/g)||[]).length,1);
assert.ok(readFileSync('client/src/components/Footer.tsx','utf8').includes('href="/chatgpt"'));
assert.ok(readFileSync('client/src/pages/features.tsx','utf8').includes('href="/chatgpt"'));
assert.ok((await renderSeoHtml('/features',template))?.includes('href="/chatgpt"'),'server-rendered feature page must link the landing page');
const app=readFileSync('client/src/App.tsx','utf8');
assert.ok(app.includes('lazy(() => import("@/pages/chatgpt"))'),'page must be lazy-loaded');
assert.ok(app.includes('path="/chatgpt" component={ChatGPTPage}'));
for (const entry of ['server/workerStatic.ts','server/index-prod.ts']) {
  const source=readFileSync(entry,'utf8');
  assert.match(source,/const KNOWN_STATIC_ROUTES = new Set\(\[\s*CHATGPT_PLUGIN.path,/,'production must not return a soft/real 404 for the new static route');
}
assert.equal(isAgentPublicPage(CHATGPT_PLUGIN.path),true);
assert.ok(publicPageMarkdown(CHATGPT_PLUGIN.path,html,'https://nycschoolsratings.com')?.includes(CHATGPT_PLUGIN.url));
console.log('ChatGPT landing: verified listing URL, shared SSR/client copy, SEO, unique schemas, FAQs, public/private boundaries, prompts, lazy route, sitemap and internal links passed.');
